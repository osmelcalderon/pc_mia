El porcentaje es un símbolo matemático que se denota de esta forma %
Representa una cantidad dada como una fracción en 100 partes iguales. 
  Ejemplos: 
     Imaginate que tienes un solo pastel grande y 100 invitados en tu fiesta, para quedar bien debes picarlo a partes iguales, cada tajada que das es 1 % de todo el pastel

También se le llama comúnmente como "tanto por ciento".... donde la palabra "por ciento" significa «de cada cien unidades». 
	Ejemplo: imaginate, que de pronto todos los invitados se te fueron y ya habías picado el pastel en 100 unidades y solo quedaron 5 invitados bien golosos, ....  ahora agarras 20pedacito y se lo das a cada uno.... eso significa que distes el " 20 % de las 100 unidades que tenias encima de la mesa"

 
 
 En fin se usa para definir relaciones entre dos cantidades:
 	 -De forma que el tanto por ciento de una cantidad, donde la palabra "tanto" es un número....... y se refiere a la parte proporcional a ese número de unidades de cada cien de esa cantidad.

 	 Ejemplo: Imaginate que una de esas personas llego a su casa y tuvo que dividir el pastel con su hermano....  Pero es tan goloso, que le dijo, sabes yo solo te voy a dar el 25% de lo que traje.......
 	   Pues ahí va la pregunta.... como el saca la parte proporcional de esos 20 pedazos...



