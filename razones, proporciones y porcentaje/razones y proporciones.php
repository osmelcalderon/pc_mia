 razón: Era el resultado de la comparación entre 2 números
 Proporción: La proporcion es la igualdad de 2 razones

1- Expresa la razón de un aula donde hay 8 indisciplinados y 22 disciplinados

  indisciplinados/disciplinados  = 8/22
  4/11  = hay 4 indisciplinados por cada 11 disciplinados.... lo que es lo mismo que "4 es a 11"

2- En un aula donde hay 32 alumnos hay 24 varones... cual es su razón?

  hembras/varones = 8/24
  1/3   = hay 1 hembra por cada 4 varones.... lo que es lo mismo que "1 es a 3".... o hay un tercio de hembras en el aula


3- verificar si es una proporción?
4/3 = 8/6    4*6 = 8*3       24 = 24. Existe proporcion porque hay igualdad entre razones

4/2= 5/6    4*6 = 2*5      24 = 10    No hay proporción , porque hay desigualdad entre razones

4- encuentra el valor desconocido en la siguiente proporción?

    3/5=x/20
       x = (20*3)/5 = 12

     3/5 = 12/20   Aqui esta la proporción planteada
     3*20 = 12*5     60   = 60 ... Donde hay una proporción porque existe igualdad entre razones

